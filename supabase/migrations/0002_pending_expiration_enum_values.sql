--
-- PostgreSQL (מ-9.1, וטרנזקציונלי החל מ-12): ALTER TYPE ... ADD VALUE מותר
-- בתוך בלוק טרנזקציה, אבל הערך החדש "לא ניתן לשימוש" (בפקודת DML בפועל —
-- INSERT/UPDATE/השוואה) עד שהטרנזקציה שהוסיפה אותו התחייבה (COMMIT).
--
-- אם Supabase SQL Editor שולח קובץ SQL שלם עם כמה פקודות כ"simple query"
-- אחת, Postgres עוטף את כולן implicitly בטרנזקציה אחת. אילו הפקודות האלה
-- היו יושבות באותו קובץ כמו 0003 (שמכיל CREATE FUNCTION עם 'expired' בגוף
-- הפונקציה), זה עדיין היה בטוח כשלעצמו — CREATE FUNCTION לא מריץ את גוף
-- הפונקציה, רק שומר אותו כטקסט. אבל כדי לא להישען על הבטחה עדינה כזו מול
-- פרויקט Supabase אמיתי (ולא סביבת בדיקה מקומית), ולמנוע כל תרחיש קצה
-- עתידי (כגון תוספת עתידית לקובץ שכן תנסה להשתמש בערך בפועל), הערכים
-- מבודדים כאן, בקובץ ובטרנזקציה נפרדים משלהם.
--
-- הרצה ב-Supabase SQL Editor: יש להריץ קובץ זה לבד, ולוודא שהוא הצליח
-- ו-commit-לפני שמריצים את 0003_pending_expiration.sql.
-- ============================================================================

alter type appointment_status add value 'expired';
