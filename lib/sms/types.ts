/**
 * שכבת שליחת הודעות — חוזה משותף לכל הספקים.
 *
 * המערכת לא יודעת מי הספק. כל קוד שרוצה לשלוח SMS קורא ל-getSmsProvider()
 * ומקבל מימוש שתואם לממשק הזה. החלפת ספק בעתיד = הוספת קובץ אחד ושינוי
 * משתנה סביבה, בלי לגעת בלוגיקת ההזמנות או האימות.
 *
 * אין מפתחות בקוד — כל פרטי הגישה מגיעים ממשתני סביבה.
 */

/** סוגי ההודעות שהמערכת שולחת — משמש ללוגים, למדידה ולבחירת תבנית */
export type SmsKind =
  | 'otp'                  // קוד התחברות / אימות
  | 'booking_confirmed'    // אישור קביעת תור
  | 'booking_rescheduled'  // אישור שינוי מועד
  | 'booking_cancelled'    // אישור ביטול
  | 'reminder'             // תזכורת לפני התור
  | 'admin_notice'         // עדכון לבעלת העסק

export interface SmsMessage {
  /** יעד בפורמט E.164 בלבד (ראה lib/phone.ts) */
  to: string
  body: string
  kind: SmsKind
}

export interface SmsResult {
  ok: boolean
  /**
   * ⚠️ הבקשה יצאה ואיננו יודעים מה עלה בגורלה — timeout, חיבור שנקטע אחרי
   * שנוצר, או תשובה שאי אפשר לפענח. **`ok` נשאר true.**
   *
   * זו החלטה מכוונת, ולא רישול: מנוע התזכורות מבחין בין ארבע תוצאות, ואילו
   * `SmsResult` הוא בינארי. מיפוי התוצאה העמומה ל-`ok:false` היה מציג
   * "לא הצלחנו לשלוח" ללקוחה שההודעה **כן** הגיעה אליה, ונועל אותה 60
   * שניות עם קוד תקף ביד. שורת ה-OTP נשארת תקפה, המסך ממשיך להזנת הקוד,
   * ומוצגת הודעה כללית.
   *
   * 🔒 **אין retry אוטומטי על תוצאה עמומה.** ל-019 אין idempotency מוכחת,
   * ולכן ניסיון נוסף אינו "ניסיון" אלא הימור על SMS שני ללקוחה.
   */
  uncertain?: boolean
  /**
   * 🔒 **הוכח שההודעה לא התקבלה למשלוח.** לא "כנראה", ולא "השליחה החזירה
   * שגיאה" — הוכח.
   *
   * ⚠️ הדגל הזה הוא היחיד שמתיר למחוק את שורת ה-OTP שנוצרה לפני השליחה.
   * שורה שנשארת אחרי כשל ודאי היא הקוד "האחרון", ולכן היא **מבטלת קוד קודם
   * שאולי כבר הגיע ללקוחה**, מפעילה cooldown, ונספרת במכסות — כלומר מענישה
   * את הלקוחה על תקלה אצלנו.
   *
   * ⚠️ `uncertain` ו-`notDelivered` **לעולם אינם מופיעים יחד**. תוצאה עמומה
   * אינה הוכחה לכלום, ומחיקת השורה שם הייתה משאירה את הלקוחה עם SMS ובו קוד
   * שהמערכת כבר אינה מכירה.
   *
   * ⚠️ ספק שזרק חריגה **אינו** מסמן את הדגל: חריגה באמצע fetch יכולה לקרות
   * גם אחרי שהבקשה יצאה. ברירת המחדל היא לא למחוק.
   */
  notDelivered?: boolean
  /** מזהה ההודעה אצל הספק — נשמר בלוג לצורך מעקב ותחקור */
  providerMessageId?: string
  error?: string
}

export interface SmsProvider {
  /** שם הספק — ללוגים ולבדיקות בריאות */
  readonly name: string
  /**
   * האם הספק שולח הודעות אמיתיות. false = מצב פיתוח (הקוד מודפס לקונסול).
   * מסכי ה-UI לא משתנים לפיו — הוא נועד ללוגים ולבדיקות בלבד.
   */
  readonly isLive: boolean
  send(message: SmsMessage): Promise<SmsResult>
}
