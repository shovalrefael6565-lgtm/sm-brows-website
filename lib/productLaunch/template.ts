import 'server-only'

import { SITE_URL } from '@/lib/utils'
import type { Product } from '@/lib/data'

/**
 * נוסח הודעת ההשקה.
 *
 * ═══ 🔒 הנוסח נבנה **כולו** בשרת ═══
 *
 * ⚠️ אין כאן פרמטר `body` ואין פרמטר `url`. מסך הניהול שולח מזהה מוצר
 * בלבד, וה-API גוזר מכאן את הטקסט ואת הקישור. לקוח שיכול להכתיב גוף
 * הודעה הוא לקוח שיכול לשלוח כל דבר בשם העסק לרשימת טלפונים.
 *
 * ⚠️ `productUrl` נגזר מ-`SITE_URL` (lib/utils.ts) ומה-slug של המוצר
 * בקטלוג — שני מקורות שרת. אין מסלול שבו כתובת מהדפדפן מגיעה להודעה.
 *
 * ═══ 🔒 מה הנוסח **אינו** מכיל, ובמכוון ═══
 *
 *   ❌ מבצע, הנחה או קוד קופון.
 *   ❌ מוצרים נוספים או המלצות.
 *   ❌ קריאה להצטרף לדיוור.
 *   ❌ קישור הסרה מדיוור.
 *
 * הארבעה הראשונים הופכים את ההודעה מ"מימוש בקשה" ל"דבר פרסומת", וזו בדיוק
 * ההבחנה שעליה נשענת הודעת הפרטיות (PRODUCT_INTEREST_PRIVACY_NOTICE)
 * כשהיא מצהירה שההרשמה אינה הסכמה לדיוור.
 *
 * 🔴 הרביעי נעדר מסיבה הפוכה וחשובה לא פחות: קישור הסרה שייך להודעה
 * שיווקית שיש ממנה "הסרה". כאן נשלחת הודעה **אחת**, שהלקוחה ביקשה
 * במפורש, ואין רשימה שוטפת להסיר ממנה. הוספת קישור הסרה הייתה מרמזת על
 * דיוור מתמשך שאינו קיים.
 */

/** 🔒 תקרה שמרנית לגוף ההודעה — נבדקת לפני שליחה. */
export const LAUNCH_SMS_MAX_LENGTH = 300

export interface LaunchMessage {
  body: string
  productUrl: string
}

/**
 * בונה את ההודעה למוצר.
 *
 * ⚠️ מוצר בלי slug אינו יכול לקבל הודעה — אין לו כתובת לשלוח אליה.
 */
export function buildLaunchMessage(product: Product): LaunchMessage | null {
  if (!product.slug) return null

  const productUrl = `${SITE_URL}/shop/${product.slug}`
  const name = product.shortName ?? product.name

  /*
   * ⚠️ הנוסח קבוע ואינו מורכב משדות של המוצר מלבד השם והקישור. תיאור
   * השיווקי של המוצר אינו נכנס להודעה: הוא משתנה בלי שאיש חושב על
   * האורך או על הטון של SMS.
   */
  const body =
    `היי 🤎 ביקשת שנעדכן כשה-${name} של SHOVAL MIARA יעלה לאתר. `
    + `המוצר זמין עכשיו: ${productUrl}`

  return { body, productUrl }
}

/**
 * מפתח ה-idempotency שנשלח לספק.
 *
 * ⚠️ מזהה השורה, ו**לעולם לא** חותמת זמן, מספר ניסיון או מזהה ריצה: הוא
 * חייב להיות זהה בכל ניסיון חוזר של אותה הרשמה.
 *
 * 🔴 אצל 019 הוא נשלח כ-external_id, שהוא **client reference לצורכי DLR
 * בלבד**. התיעוד של הספק אינו מתחייב שהוא ייחודי ואינו מתחייב שהוא מונע
 * כפילות — ראה lib/reminders/types.ts. לכן ההגנה האמיתית מפני שליחה
 * כפולה היא המעבר האטומי open→notified ב-DB (0039), ולא המפתח הזה.
 */
export function launchIdempotencyKey(requestId: string): string {
  return `product-launch:${requestId}`
}
