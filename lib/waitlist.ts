/**
 * רשימת המתנה — **שכבה נוספת מעל מנגנון הזמינות הקיים, ולא שינוי שלו.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ═══ מה הקובץ הזה כן עושה ═══
 *
 * מחשב את `WAITLIST OPTIONS` בהגדרה אחת בלבד:
 *
 *     WAITLIST OPTIONS = legalStartTimes(...)  MINUS  selectDisplaySlots(...)
 *
 * שני האגפים נלקחים מ-lib/slotSelection.ts, ושניהם שואבים מאותו מאגר
 * (`legalFreeSlots`). לכן:
 *
 *   • כל שעה שמוצגת כאן היא שעה חוקית ופנויה **באמת** — היא עברה בדיוק
 *     את אותן בדיקות שהזמינות הציבורית עוברת: שישי/שבת, רשת שעות העבודה,
 *     טווח ה-30 יום, חלון ההכנה, ואי-חפיפה מול Google Calendar ומול
 *     תורים/pending ב-DB (busyRanges).
 *   • שום שעה שכבר מוצגת ללקוחה לא תופיע כאן — היא מחוסרת במפורש.
 *
 * ═══ 🔒 מה הקובץ הזה **אינו** עושה ═══
 *
 *   ❌ אינו מרחיב את הזמינות הציבורית. `selectDisplaySlots` נקראת כאן
 *      כקריאה טהורה לצורך *חיסור*, ולא שונתה.
 *   ❌ אינו פותח שעות, ימים או תאריכים שהמנגנון הקיים סוגר. יום חסום,
 *      שבת, חג, יום מחוץ לטווח או יום שכולו תפוס מגיעים לכאן עם מאגר
 *      ריק — ואז אין מה להציע.
 *   ❌ אינו עוקף את Google Calendar. `busyRanges` הוא בדיוק אותו מבנה
 *      שמחזיר `resolveAvailability` (יומן + DB ממוזגים), ואם הוא לא
 *      התקבל — הקורא חייב להתייחס לכך כ"אין תשובה", לא כ"היום פנוי".
 *
 * ⚠️ הצטרפות לרשימת המתנה אינה תור: היא אינה חוסמת סלוט, אינה נכנסת
 * ל-busyRanges ואינה יוצרת אירוע ביומן. ראה ההערה במסלול השמירה.
 * ────────────────────────────────────────────────────────────────────────────
 */

import {
  legalStartTimes, selectDisplaySlots, type SelectSlotsParams,
} from './slotSelection'

export type WaitlistOptionsParams = SelectSlotsParams & { durationMin: number }

/**
 * השעות שניתן להציע ברשימת ההמתנה לאותו יום: כל השעות החוקיות והפנויות
 * שאינן מוצגות כרגע בקביעת התור הרגילה.
 *
 * מוחזר ממוין עולה. רשימה ריקה = "אין כרגע שעות נוספות ליום הזה" — לא
 * שגיאה, ולא סיבה להציג משהו אחר.
 */
export function selectWaitlistOptions(params: WaitlistOptionsParams): string[] {
  const shown = new Set(selectDisplaySlots(params))
  return legalStartTimes(params).filter(slot => !shown.has(slot))
}

/**
 * האם שעה מסוימת חוקית ופנויה **באמת** לאותו יום ולאותו משך.
 *
 * 🔒 זו בדיקת ה-revalidation לפני שמירת בקשת המתנה. היא בכוונה בודקת
 * חוקיות+פנויות בלבד, ו**לא** את החיסור מהמוצג:
 *
 * ⚠️ ההצגה הציבורית תלויה בזמן (חלון ההכנה זז עם השעון) ובזרע התאריך.
 * אילו השרת היה דורש "השעה חייבת להיות מחוץ למוצג", בקשה תקינה לחלוטין
 * הייתה יכולה להידחות רק משום שדקה עברה בין הרינדור לשליחה. החיסור הוא
 * החלטת *תצוגה*; מה שחייב להיאכף בשמירה הוא שהשעה אינה תפוסה ואינה חסומה.
 */
export function isWaitlistSlotStillOpen(
  params: WaitlistOptionsParams & { time: string },
): boolean {
  return legalStartTimes(params).includes(params.time)
}
