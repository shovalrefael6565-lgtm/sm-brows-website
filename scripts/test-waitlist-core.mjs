const results = []
function chk(name, ok, extra = '') {
  results.push(ok)
  console.log(`${ok ? '✓' : '✗'} ${name}${extra ? '  ' + extra : ''}`)
}
function section(title) {
  console.log(`\n── ${title} ${'─'.repeat(Math.max(0, 54 - title.length))}`)
}

const { selectDisplaySlots, legalStartTimes } = await import('../lib/slotSelection.ts')
const { selectWaitlistOptions, isWaitlistSlotStillOpen } = await import('../lib/waitlist.ts')

/** 10:15 בשעון ישראל, יום שלישי 08.09.2026 — קבוע, כדי שהבדיקות דטרמיניסטיות */
const NOW = new Date('2026-09-08T07:15:00.000Z')

/** יום עסקים "רגיל" בתוך הטווח, רחוק מספיק כדי שהסולם יהיה 8 */
const DAY = { year: 2026, month: 8, day: 17 }   // חמישי 17.09.2026

const opts = (over = {}) =>
  ({ ...DAY, busyRanges: [], durationMin: 20, now: NOW, ...over })

// ─────────────────────────────────────────────────────────────────────────────
section('1+2 — ההגדרה: חוקי ופנוי MINUS מוצג')

{
  const p = opts()
  const publicSlots = selectDisplaySlots(p)
  const legal = legalStartTimes(p)
  const waitlist = selectWaitlistOptions(p)

  chk('🔒 אף סלוט ציבורי אינו מופיע ברשימת ההמתנה',
    publicSlots.every(s => !waitlist.includes(s)),
    `ציבורי=${publicSlots.length} המתנה=${waitlist.length}`)

  chk('סלוט חוקי ופנוי שלא נחשף לציבור — כן מופיע',
    waitlist.length > 0 && waitlist.every(s => legal.includes(s)))

  chk('האיחוד מכסה בדיוק את כל החוקיים והפנויים',
    new Set([...publicSlots, ...waitlist]).size === legal.length &&
    legal.every(s => publicSlots.includes(s) || waitlist.includes(s)))

  chk('אין כפילויות ברשימת ההמתנה', new Set(waitlist).size === waitlist.length)
  chk('הרשימה ממוינת עולה',
    waitlist.every((s, i) => i === 0 || s > waitlist[i - 1]))
}

