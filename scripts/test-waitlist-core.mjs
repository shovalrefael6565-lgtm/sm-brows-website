section('3+4 — תור קיים / אירוע Google לא מופיעים')

{
  // ⚠️ שני המקורות מגיעים לכאן באותו מבנה בדיוק (resolveAvailability ממזג
  // אותם), ולכן בדיקה אחת מכסה את שניהם — ואין דרך שלישית להגיע למאגר.
  const appointment = { start: '17:00', end: '17:20' }   // תור מה-DB
  const googleEvent = { start: '10:00', end: '11:00' }   // אירוע ביומן
  const w = selectWaitlistOptions(opts({ busyRanges: [appointment, googleEvent] }))

  chk('תור קיים (DB) אינו ברשימת ההמתנה', !w.includes('17:00'))
  chk('אירוע Google Calendar אינו ברשימת ההמתנה',
    !w.includes('10:00') && !w.includes('10:20') && !w.includes('10:40'))
  chk('שעה סמוכה שכן פנויה נשארת אפשרית', w.includes('17:20') || selectDisplaySlots(opts({ busyRanges: [appointment, googleEvent] })).includes('17:20'))
  chk('🔒 אף שעה ברשימה אינה חופפת טווח תפוסה',
    w.every(s => {
      const m = Number(s.slice(0, 2)) * 60 + Number(s.slice(3))
      return ![appointment, googleEvent].some(b => {
        const bs = Number(b.start.slice(0, 2)) * 60 + Number(b.start.slice(3))
        const be = Number(b.end.slice(0, 2)) * 60 + Number(b.end.slice(3))
        return bs < m + 20 && be > m
      })
    }))
}

